    <h3>1. Política general</h3>
    <p>Las compras de contenido digital se consideran finales una vez que los WCoin C, días VIP o beneficios correspondientes fueron acreditados correctamente en la cuenta. MU PANIC no ofrece reembolsos voluntarios por cambio de opinión, arrepentimiento posterior al uso, pérdida de interés en el servidor o uso parcial del beneficio adquirido.</p>

    <h3>2. Excepciones</h3>
    <p>Podrá revisarse una operación cuando exista alguno de los siguientes supuestos:</p>
    <ul>
        <li>cobro duplicado;</li>
        <li>pago aprobado sin acreditación del beneficio correspondiente;</li>
        <li>acreditación manifiestamente incorrecta causada por un error técnico de MU PANIC;</li>
        <li>operación que deba ser revertida por obligación legal o por resolución del proveedor de pagos.</li>
    </ul>

    <h3>3. WCoin C o beneficios ya utilizados</h3>
    <p>Si los WCoin C, ítems, días VIP u otros beneficios ya fueron utilizados, transferidos, consumidos o generaron ventajas dentro del juego, la operación normalmente no será reembolsable, salvo que la normativa aplicable disponga otra cosa.</p>

    <h3>4. Contracargos y desconocimientos</h3>
    <p>Antes de iniciar un contracargo o desconocimiento, contactá al soporte para revisar el caso. Los contracargos fraudulentos, abusivos o realizados después de consumir los beneficios pueden dar lugar a suspensión preventiva de la cuenta mientras se investiga la operación.</p>

    <h3>5. Errores al comprar</h3>
    <p>Antes de confirmar el pago, verificá la cuenta, el paquete, el importe y el medio de pago. MU PANIC no puede garantizar la reversión de compras correctamente acreditadas cuando el error provenga de datos ingresados o seleccionados por el usuario.</p>

    <h3>6. Cómo solicitar una revisión</h3>
    <p>Si detectás un cobro duplicado, una acreditación faltante o un error técnico, contactá cuanto antes al <a href="https://discord.gg/fP4Mxcsee" target="_blank" rel="noopener noreferrer">soporte oficial de MU PANIC</a> e informá los datos necesarios para identificar la operación. No publiques comprobantes ni información sensible en canales públicos.</p>

    <h3>7. Legislación aplicable</h3>
    <p>Esta política se aplica sin limitar los derechos inderogables que correspondan a consumidores y usuarios según la legislación aplicable en la República Argentina.</p>

